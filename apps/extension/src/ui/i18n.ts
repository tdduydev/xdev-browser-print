const dictionaries: Record<Language, Record<Key, string>> = { vi, en };
let current: Language = 'vi';

export type I18nKey = Key;

export function setLanguage(lang: Language) {
  current = lang;
  document.documentElement.lang = lang;
}

export function getLanguage(): Language {
  return current;
}

export async function loadLanguage(): Promise<Language> {
  const r = await chrome.storage.local.get('config');
  const lang = (r.config as { settings?: { language?: Language } } | undefined)?.settings?.language;
  setLanguage(lang === 'en' ? 'en' : 'vi');
  return current;
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = dictionaries[current][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
